import { test, expect } from "@playwright/test";

test("管理端 mock 流程支持导入、连接验证、依赖和未保存保护", async ({ page }) => {
  await page.route("**/api/auth/me", route => route.fulfill({ json: { userId: 1, name: "管理员", phone: "000", admin: true } }));
  await page.goto("/");
  await page.getByRole("button", { name: "管理界面" }).click();
  await page.getByRole("button", { name: "Skills 管理" }).click();
  await page.getByRole("button", { name: "导入 Skill 包" }).click();
  await page.getByRole("button", { name: "使用示例包" }).click();
  await page.getByRole("button", { name: "下一步" }).click();
  await page.getByRole("button", { name: "下一步" }).click();
  await page.getByLabel(/查询会议室/).check();
  await page.getByRole("button", { name: "创建草稿" }).click();
  await expect(page.getByText("已创建 会议预订（导入） 的演示草稿")).toBeVisible();
  await page.getByRole("button", { name: "返回列表" }).last().click();
  await page.getByRole("button", { name: "MCP 管理" }).click();
  await page.getByRole("button", { name: "新增 MCP" }).click();
  await page.getByPlaceholder("请输入名称").fill("测试服务");
  await page.getByPlaceholder("例如 meeting-booking").fill("test-service");
  await page.getByRole("button", { name: "下一步" }).click();
  await page.getByPlaceholder("https://example.com/mcp").fill("https://fail.example.com/mcp");
  await page.getByRole("button", { name: "下一步" }).click();
  await page.getByRole("button", { name: "验证连接并发现工具" }).click();
  await expect(page.getByText(/连接失败（模拟）/)).toBeVisible();
  await page.getByRole("button", { name: "上一步" }).click();
  await page.getByPlaceholder("https://example.com/mcp").fill("https://example.com/mcp");
  await page.getByRole("button", { name: "下一步" }).click();
  await page.getByRole("button", { name: "验证连接并发现工具" }).click();
  await page.getByRole("button", { name: "保存 MCP" }).click();
  await page.getByRole("button", { name: "返回列表" }).last().click();
  await expect(page.getByRole("button", { name: "测试服务", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Agent 管理" }).click();
  await page.getByRole("button", { name: "海卓大脑办公助手", exact: true }).click();
  await page.getByRole("button", { name: "能力配置", exact: true }).click();
  await page.getByLabel(/会议室查询/).check();
  await page.getByRole("button", { name: "返回列表" }).first().click();
  await expect(page.getByRole("dialog", { name: "尚有未保存的修改" })).toBeVisible();
  await page.getByRole("button", { name: "继续编辑" }).click();
  await page.getByRole("button", { name: "保存草稿" }).first().click();
  await page.getByRole("button", { name: "返回列表" }).first().click();
  await page.getByRole("button", { name: "Skills 管理" }).click();
  await expect(page.getByRole("button", { name: "会议预订（导入）", exact: true })).toBeVisible();
});
