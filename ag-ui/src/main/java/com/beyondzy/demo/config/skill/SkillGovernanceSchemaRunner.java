package com.beyondzy.demo.config.skill;

import java.sql.Connection;
import java.sql.SQLException;
import javax.sql.DataSource;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

/**
 * 启动时补技能治理缺的列和绑定表。可以重复执行。
 *
 * <p>不修改已有 source，也不删除索引。只在本次启动新建 ai_agent_skill 时，
 * 把当时已经存在的技能绑到 session-chat；之后新增的技能不会在重启时被自动绑上。
 */
@Component
@Order(2)
public class SkillGovernanceSchemaRunner implements ApplicationRunner {
    private static final String SKILLS = "agentscope_skills";
    private static final String BINDING = "ai_agent_skill";

    private final JdbcTemplate jdbc;

    public SkillGovernanceSchemaRunner(DataSource dataSource) {
        this.jdbc = new JdbcTemplate(dataSource);
    }

    @Override
    public void run(ApplicationArguments args) {
        ensure();
    }

    /** 给测试和启动共用。技能主表不存在时直接失败，不在这里代跑 V6。 */
    public void ensure() {
        if (!tableExists(SKILLS)) {
            throw new IllegalStateException("缺少 agentscope_skills，请先执行 V6__agent_skill.sql");
        }
        String dept = h2() ? "BIGINT NULL" : "BIGINT UNSIGNED NULL";
        addColumn("status", "CHAR(1) NOT NULL DEFAULT '0'");
        addColumn("visible_scope", "CHAR(1) NOT NULL DEFAULT '0'");
        addColumn("owner_dept_id", dept);
        addColumn("create_by", dept);
        boolean createdBinding = !tableExists(BINDING);
        if (createdBinding) {
            jdbc.execute(h2() ? h2BindingTable() : mysqlBindingTable());
            if (h2()) {
                jdbc.execute("CREATE INDEX idx_ai_agent_skill_skill ON ai_agent_skill (skill_id)");
            }
            bindSkillsPresentAtUpgrade();
        }
    }

    private boolean h2() {
        DataSource dataSource = jdbc.getDataSource();
        if (dataSource == null) return false;
        try (Connection connection = dataSource.getConnection()) {
            return connection.getMetaData().getDatabaseProductName().toLowerCase().contains("h2");
        } catch (SQLException error) {
            throw new IllegalStateException("无法识别数据库产品", error);
        }
    }

    /** 与 V11 同一张表。生产用自增，测试库用 H2 能执行的身份列。 */
    private static String mysqlBindingTable() {
        return """
                CREATE TABLE ai_agent_skill (
                    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
                    agent_id VARCHAR(128) NOT NULL,
                    skill_id BIGINT NOT NULL,
                    created_by BIGINT UNSIGNED NOT NULL,
                    gmt_create DATETIME(3) NOT NULL,
                    gmt_modified DATETIME(3) NOT NULL,
                    UNIQUE KEY uk_ai_agent_skill (agent_id, skill_id),
                    KEY idx_ai_agent_skill_skill (skill_id)
                ) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci
                """;
    }

    private static String h2BindingTable() {
        return """
                CREATE TABLE ai_agent_skill (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    agent_id VARCHAR(128) NOT NULL,
                    skill_id BIGINT NOT NULL,
                    created_by BIGINT NOT NULL,
                    gmt_create TIMESTAMP(3) NOT NULL,
                    gmt_modified TIMESTAMP(3) NOT NULL,
                    CONSTRAINT uk_ai_agent_skill UNIQUE (agent_id, skill_id)
                )
                """;
    }

    private void addColumn(String column, String definition) {
        if (columnExists(SKILLS, column)) return;
        jdbc.execute("ALTER TABLE " + SKILLS + " ADD COLUMN " + column + " " + definition);
    }

    /**
     * 只在绑定表刚刚建出来时调用。优先取管理员，没有就取最小的未删除用户；用户表空着就跳过。
     */
    private void bindSkillsPresentAtUpgrade() {
        if (!tableExists("app_user") || !columnExists("app_user", "is_deleted")) return;
        String order = columnExists("app_user", "is_admin")
                ? "ORDER BY CASE WHEN is_admin = 1 THEN 0 ELSE 1 END, id"
                : "ORDER BY id";
        Long actor = jdbc.query("SELECT id FROM app_user WHERE is_deleted = 0 " + order + " LIMIT 1",
                rs -> rs.next() ? rs.getLong(1) : null);
        if (actor == null) return;
        jdbc.update("""
                INSERT INTO ai_agent_skill (agent_id, skill_id, created_by, gmt_create, gmt_modified)
                SELECT ?, s.id, ?, CURRENT_TIMESTAMP(3), CURRENT_TIMESTAMP(3)
                FROM agentscope_skills s
                WHERE NOT EXISTS (
                    SELECT 1 FROM ai_agent_skill existing
                    WHERE existing.agent_id = ? AND existing.skill_id = s.id
                )
                """, SkillJdbc.SESSION_AGENT, actor, SkillJdbc.SESSION_AGENT);
    }

    private boolean tableExists(String table) {
        Integer count = jdbc.queryForObject("""
                SELECT COUNT(*) FROM information_schema.tables
                WHERE UPPER(table_schema) = UPPER(?) AND UPPER(table_name) = UPPER(?)
                """, Integer.class, schema(), table);
        return count != null && count > 0;
    }

    private boolean columnExists(String table, String column) {
        Integer count = jdbc.queryForObject("""
                SELECT COUNT(*) FROM information_schema.columns
                WHERE UPPER(table_schema) = UPPER(?)
                  AND UPPER(table_name) = UPPER(?)
                  AND UPPER(column_name) = UPPER(?)
                """, Integer.class, schema(), table, column);
        return count != null && count > 0;
    }

    private String schema() {
        String schema = jdbc.queryForObject("SELECT SCHEMA()", String.class);
        if (schema == null || schema.isBlank()) {
            throw new IllegalStateException("无法确定当前数据库 schema");
        }
        return schema;
    }
}
